"""Create an isolated Codex home for each AutoSFT run."""

from __future__ import annotations

import json
import os
import shutil
from collections.abc import Callable
from pathlib import Path


AUTO_SFT_CODEX_PROFILE = "autosft"


def source_codex_home() -> Path:
    """Codex home configured for this machine, before per-run isolation."""
    return Path(os.environ.get("CODEX_HOME") or (Path.home() / ".codex")).expanduser()


def prepare_run_codex_home(
    run_dir: Path,
    *,
    project_root: Path | None = None,
    source_home: Path | None = None,
    warn: Callable[[str], None] | None = None,
) -> Path:
    """Seed and return ``<run_dir>/codex_home``.

    Authentication and provider configuration come from the machine-level
    Codex home. The generated AutoSFT profile trusts this checkout without
    requiring users to edit their global config. Agent settings are passed
    explicitly by the launchers. Session history, rollouts, logs,
    and other runtime state are then written to the run-local home by callers
    that export the returned path as ``CODEX_HOME``.

    This is idempotent, so a caller may re-run it before every agent attempt to
    repair a run-local home that went stale mid-run. Such a caller must pass
    ``source_home`` explicitly: once it has exported the run-local path as
    ``CODEX_HOME``, :func:`source_codex_home` would otherwise resolve to the
    destination and the seeding step would be skipped.
    """
    dst = Path(run_dir) / "codex_home"
    dst.mkdir(parents=True, exist_ok=True)
    # auth.json carries live API credentials; the machine-level source may be
    # 644 and copy2 preserves the source mode, so tighten both the home and
    # every seeded file explicitly (mkdir exist_ok never re-sets the mode).
    dst.chmod(0o700)
    src = Path(source_home) if source_home is not None else source_codex_home()

    try:
        same_home = src.resolve() == dst.resolve()
    except OSError:
        same_home = src.absolute() == dst.absolute()
    if not same_home:
        for name in ("auth.json", "config.toml"):
            source_file = src / name
            if not source_file.is_file():
                continue
            try:
                shutil.copy2(source_file, dst / name)
                (dst / name).chmod(0o600)
            except OSError as exc:
                if warn is not None:
                    warn(f"could not seed {name} into per-run CODEX_HOME: {exc}")

    checkout = (project_root or Path(__file__).resolve().parents[3]).resolve()
    quoted_checkout = json.dumps(str(checkout), ensure_ascii=True)
    profile = dst / f"{AUTO_SFT_CODEX_PROFILE}.config.toml"
    profile.write_text(
        "# Generated by AutoSFT for this isolated run.\n"
        f"[projects.{quoted_checkout}]\n"
        'trust_level = "trusted"\n',
        encoding="utf-8",
    )

    return dst
